
CREATE TABLE IF NOT EXISTS papers(
  paper_id TEXT PRIMARY KEY,
  title TEXT NOT NULL DEFAULT '',
  grade TEXT NOT NULL DEFAULT '',
  subject TEXT NOT NULL DEFAULT '',
  source_archive TEXT NOT NULL DEFAULT '',
  expected_state TEXT NOT NULL DEFAULT 'unknown'
    CHECK(expected_state IN ('unknown','confirmed')),
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS paper_items(
  paper_id TEXT NOT NULL REFERENCES papers(paper_id),
  question_number INTEGER NOT NULL CHECK(question_number >= 1),
  item_id TEXT,
  section_title TEXT NOT NULL DEFAULT '',
  PRIMARY KEY(paper_id, question_number)
);

CREATE TABLE IF NOT EXISTS items(
  item_id TEXT PRIMARY KEY,
  paper_id TEXT NOT NULL REFERENCES papers(paper_id),
  question_number INTEGER NOT NULL CHECK(question_number >= 1),
  current_revision INTEGER,
  created_at TEXT NOT NULL,
  UNIQUE(paper_id, question_number)
);

CREATE TABLE IF NOT EXISTS revisions(
  item_id TEXT NOT NULL REFERENCES items(item_id),
  revision INTEGER NOT NULL CHECK(revision > 0),
  parent_revision INTEGER,
  model_version TEXT NOT NULL,
  hash_version INTEGER NOT NULL,
  content_hash TEXT NOT NULL,
  content TEXT NOT NULL,
  actor_kind TEXT NOT NULL CHECK(actor_kind IN ('ai','human','system')),
  actor_id TEXT NOT NULL DEFAULT '',
  origin_submission_id TEXT,
  origin_operation_id TEXT,
  created_at TEXT NOT NULL,
  PRIMARY KEY(item_id, revision)
);

CREATE TABLE IF NOT EXISTS assets(
  asset_id TEXT PRIMARY KEY,
  sha256 TEXT NOT NULL UNIQUE,
  path TEXT NOT NULL UNIQUE,
  mime TEXT NOT NULL,
  size_bytes INTEGER NOT NULL CHECK(size_bytes >= 0),
  width INTEGER,
  height INTEGER,
  source_kind TEXT NOT NULL DEFAULT 'imported'
    CHECK(source_kind IN ('imported','source_page','manual','recording')),
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS revision_assets(
  item_id TEXT NOT NULL,
  revision INTEGER NOT NULL,
  binding_key TEXT NOT NULL,
  asset_id TEXT NOT NULL REFERENCES assets(asset_id),
  role TEXT NOT NULL,
  source_asset_id TEXT,
  crop_px TEXT,
  rotate INTEGER NOT NULL DEFAULT 0,
  width TEXT,
  ordinal INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY(item_id, revision, binding_key),
  FOREIGN KEY(item_id, revision) REFERENCES revisions(item_id, revision)
);

CREATE TABLE IF NOT EXISTS issues(
  item_id TEXT NOT NULL,
  revision INTEGER NOT NULL,
  issue_id TEXT NOT NULL,
  type TEXT NOT NULL,
  target TEXT NOT NULL DEFAULT '',
  reason TEXT NOT NULL DEFAULT '',
  evidence TEXT NOT NULL DEFAULT '',
  blocking INTEGER NOT NULL DEFAULT 1,
  state TEXT NOT NULL DEFAULT 'open'
    CHECK(state IN ('open','resolved','dismissed')),
  resolution TEXT,
  PRIMARY KEY(item_id, revision, issue_id),
  FOREIGN KEY(item_id, revision) REFERENCES revisions(item_id, revision)
);

CREATE TABLE IF NOT EXISTS checks(
  check_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id TEXT NOT NULL,
  revision INTEGER NOT NULL,
  validator TEXT NOT NULL,
  validator_version TEXT NOT NULL,
  passed INTEGER NOT NULL,
  errors TEXT NOT NULL DEFAULT '[]',
  created_at TEXT NOT NULL,
  FOREIGN KEY(item_id, revision) REFERENCES revisions(item_id, revision)
);

CREATE TABLE IF NOT EXISTS reviews(
  review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id TEXT NOT NULL,
  revision INTEGER NOT NULL,
  decision TEXT NOT NULL CHECK(decision IN ('approved','rejected')),
  actor_kind TEXT NOT NULL,
  actor_id TEXT NOT NULL DEFAULT '',
  note TEXT NOT NULL DEFAULT '',
  operation_id TEXT,
  created_at TEXT NOT NULL,
  FOREIGN KEY(item_id, revision) REFERENCES revisions(item_id, revision)
);

CREATE TABLE IF NOT EXISTS submissions(
  submission_id TEXT PRIMARY KEY,
  request_hash TEXT NOT NULL,
  item_key TEXT NOT NULL,
  status TEXT NOT NULL
    CHECK(status IN ('accepted','accepted_with_issues','noop','rejected','conflict')),
  item_id TEXT,
  revision INTEGER,
  content_hash TEXT,
  receipt TEXT NOT NULL,
  errors TEXT NOT NULL DEFAULT '[]',
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS operations(
  operation_id TEXT PRIMARY KEY,
  request_hash TEXT NOT NULL,
  kind TEXT NOT NULL,
  actor_kind TEXT NOT NULL,
  actor_id TEXT NOT NULL DEFAULT '',
  item_id TEXT,
  base_revision INTEGER,
  result_revision INTEGER,
  receipt TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS publications(
  publication_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id TEXT NOT NULL,
  revision INTEGER NOT NULL,
  action TEXT NOT NULL CHECK(action IN ('publish','withdraw')),
  expected_previous INTEGER,
  operation_id TEXT,
  actor_kind TEXT NOT NULL,
  actor_id TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL,
  FOREIGN KEY(item_id, revision) REFERENCES revisions(item_id, revision)
);

CREATE TABLE IF NOT EXISTS publication_heads(
  item_id TEXT PRIMARY KEY,
  publication_id INTEGER NOT NULL REFERENCES publications(publication_id)
);

CREATE TABLE IF NOT EXISTS exports(
  export_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id TEXT NOT NULL,
  revision INTEGER NOT NULL,
  exporter_version TEXT NOT NULL,
  options_hash TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK(status IN ('pending','ready','failed')),
  path TEXT,
  manifest_hash TEXT,
  error TEXT,
  created_at TEXT NOT NULL,
  completed_at TEXT,
  FOREIGN KEY(item_id, revision) REFERENCES revisions(item_id, revision),
  UNIQUE(item_id, revision, exporter_version, options_hash)
);

CREATE INDEX IF NOT EXISTS idx_paper_items_item ON paper_items(item_id);
CREATE INDEX IF NOT EXISTS idx_revisions_item_hash ON revisions(item_id, content_hash);
CREATE INDEX IF NOT EXISTS idx_revision_assets_asset ON revision_assets(asset_id);
CREATE INDEX IF NOT EXISTS idx_issues_state ON issues(item_id, revision, state, blocking);
CREATE INDEX IF NOT EXISTS idx_reviews_revision ON reviews(item_id, revision);
CREATE INDEX IF NOT EXISTS idx_checks_revision ON checks(item_id, revision, validator_version);
CREATE INDEX IF NOT EXISTS idx_publications_item ON publications(item_id, created_at);
CREATE INDEX IF NOT EXISTS idx_submissions_item ON submissions(item_id);

CREATE TABLE IF NOT EXISTS proposals(
  proposal_id TEXT PRIMARY KEY,
  item_id TEXT NOT NULL REFERENCES items(item_id),
  base_revision INTEGER NOT NULL CHECK(base_revision > 0),
  patch TEXT NOT NULL,
  reason TEXT NOT NULL DEFAULT '',
  created_by_kind TEXT NOT NULL CHECK(created_by_kind IN ('ai','human','system')),
  created_by TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'open'
    CHECK(status IN ('open','accepted','rejected','expired')),
  accepted_revision INTEGER,
  accept_operation_id TEXT,
  created_at TEXT NOT NULL,
  decided_at TEXT
);

CREATE INDEX IF NOT EXISTS idx_proposals_item ON proposals(item_id, status);

    CREATE TABLE IF NOT EXISTS teaching_notes(
      note_id TEXT PRIMARY KEY,
      item_id TEXT NOT NULL REFERENCES items(item_id),
      subquestion_id TEXT NOT NULL DEFAULT 'sq1',
      ordinal INTEGER NOT NULL DEFAULT 0,
      title TEXT NOT NULL DEFAULT '',
      current_version INTEGER,
      deleted INTEGER NOT NULL DEFAULT 0 CHECK(deleted IN (0,1)),
      deleted_at TEXT,
      created_at TEXT NOT NULL,
      updated_at TEXT NOT NULL
    );

    CREATE TABLE IF NOT EXISTS teaching_note_versions(
      note_id TEXT NOT NULL REFERENCES teaching_notes(note_id),
      version INTEGER NOT NULL CHECK(version > 0),
      parent_version INTEGER,
      base_version INTEGER,
      source_revision INTEGER NOT NULL,
      subquestion_id TEXT NOT NULL,
      subquestion_label TEXT NOT NULL DEFAULT '',
      subquestion_stem TEXT NOT NULL DEFAULT '',
      stem_fingerprint TEXT NOT NULL DEFAULT '',
      title TEXT NOT NULL DEFAULT '',
      ordinal INTEGER NOT NULL DEFAULT 0,
      explanation_text TEXT NOT NULL DEFAULT '',
      explanation_source TEXT NOT NULL DEFAULT 'manual'
        CHECK(explanation_source IN ('manual','recorded','polished','generated')),
      transcript TEXT NOT NULL DEFAULT '',
      audio_asset_id TEXT,
      solution_text TEXT NOT NULL DEFAULT '',
      solution_source TEXT NOT NULL DEFAULT 'manual'
        CHECK(solution_source IN ('manual','generated')),
      actor_kind TEXT NOT NULL CHECK(actor_kind IN ('ai','human','system')),
      actor_id TEXT NOT NULL DEFAULT '',
      operation_id TEXT,
      created_at TEXT NOT NULL,
      PRIMARY KEY(note_id, version)
    );

    CREATE TABLE IF NOT EXISTS teaching_note_reviews(
      review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      note_id TEXT NOT NULL,
      version INTEGER NOT NULL,
      decision TEXT NOT NULL CHECK(decision IN ('approved','rejected')),
      actor_kind TEXT NOT NULL,
      actor_id TEXT NOT NULL DEFAULT '',
      note TEXT NOT NULL DEFAULT '',
      operation_id TEXT,
      created_at TEXT NOT NULL
    );

    CREATE TABLE IF NOT EXISTS ai_operations(
      operation_id TEXT PRIMARY KEY,
      request_hash TEXT NOT NULL,
      kind TEXT NOT NULL,
      target TEXT NOT NULL,
      input_snapshot TEXT NOT NULL,
      state TEXT NOT NULL CHECK(state IN ('running','succeeded','failed','unknown','conflict'))
        DEFAULT 'running',
      result TEXT,
      applied INTEGER NOT NULL DEFAULT 0 CHECK(applied IN (0,1)),
      error TEXT,
      provider TEXT,
      model TEXT,
      usage TEXT,
      created_at TEXT NOT NULL,
      completed_at TEXT
    );

    CREATE TABLE IF NOT EXISTS blueprint_batches(
      batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      paper_id TEXT NOT NULL,
      manifest_hash TEXT NOT NULL,
      local_path TEXT NOT NULL,
      external_path TEXT,
      external_status TEXT NOT NULL DEFAULT 'pending'
        CHECK(external_status IN ('pending','delivered','not_configured','failed')),
      candidate_count INTEGER NOT NULL DEFAULT 0,
      created_at TEXT NOT NULL,
      UNIQUE(paper_id, manifest_hash)
    );

    CREATE TABLE IF NOT EXISTS blueprint_candidates(
      batch_id INTEGER NOT NULL REFERENCES blueprint_batches(batch_id),
      candidate_id TEXT NOT NULL,
      item_id TEXT NOT NULL,
      item_revision INTEGER NOT NULL,
      note_id TEXT NOT NULL,
      note_version INTEGER NOT NULL,
      content_hash TEXT NOT NULL,
      payload TEXT NOT NULL,
      PRIMARY KEY(batch_id, candidate_id)
    );

    CREATE INDEX IF NOT EXISTS idx_teaching_notes_item
      ON teaching_notes(item_id, subquestion_id, deleted);
    CREATE INDEX IF NOT EXISTS idx_teaching_note_reviews
      ON teaching_note_reviews(note_id, version);
    CREATE INDEX IF NOT EXISTS idx_blueprint_batches_paper
      ON blueprint_batches(paper_id, created_at);

